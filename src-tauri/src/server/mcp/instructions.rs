//! Инструкции MCP-сервера, отдаваемые агенту в `initialize.instructions`.
//!
//! Текст лежит в `instructions.md` и встраивается на этапе сборки
//! (`include_str!`) — ни I/O в рантайме, ни проблем с путями. Правило
//! разделения: **сюда — что делать и куда идти; подробности форматов — в
//! MCP-ресурсы `mai://guide/*`**, потому что инструкции агент читает всегда,
//! а ресурсы — только когда понадобились.

/// Текст инструкций сервера (глоссарий, маршрут работы, дисциплина размера).
pub const SERVER: &str = include_str!("instructions.md");

#[cfg(test)]
mod tests {
    use super::*;

    /// Разделы, без которых инструкция теряет смысл: глоссарий, маршрут,
    /// дисциплина размера. Проверка ловит случайно сокращённый файл.
    const REQUIRED: [&str; 5] = [
        "## Глоссарий",
        "## Идентификаторы",
        "## Маршрут работы",
        "## Дисциплина размера",
        "## Форматы содержимого",
    ];

    /// Мягкий потолок размера инструкций: ~3k символов ≈ 1k токенов, которые
    /// агент платит на каждой сессии. Превышение — повод унести текст в ресурс.
    const SIZE_BUDGET: usize = 4_000;

    #[test]
    fn инструкции_не_пусты_и_в_бюджете() {
        assert!(!SERVER.trim().is_empty());
        assert!(
            SERVER.chars().count() <= SIZE_BUDGET,
            "инструкции разрослись до {} символов (бюджет {SIZE_BUDGET})",
            SERVER.chars().count()
        );
    }

    #[test]
    fn все_обязательные_разделы_на_месте() {
        for section in REQUIRED {
            assert!(SERVER.contains(section), "нет раздела «{section}»");
        }
    }

    #[test]
    fn инструкции_ссылаются_на_существующие_инструменты() {
        for tool in [
            "mai_list_courses",
            "mai_course_outline",
            "mai_get_resource",
            "mai_get_content",
            "mai_search",
        ] {
            assert!(SERVER.contains(tool), "инструкции не упоминают {tool}");
        }
    }
}
