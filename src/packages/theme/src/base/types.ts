import type { AppTheme } from './theme'

/**
 * Имя дизайна темы. Каждый дизайн содержит светлую и тёмную вариации.
 *
 * При добавлении нового дизайна его идентификатор нужно добавить в этот тип
 * и зарегистрировать соответствующий набор токенов в `registry.ts`.
 */
export type ThemeName = 'default'

/**
 * Светлая или тёмная вариация выбранного дизайна.
 */
export type ThemeMode = 'light' | 'dark'

/**
 * Предпочтение пользователя для выбора вариации темы.
 * Значение `system` разрешается провайдером через системную цветовую схему.
 */
export type ThemePreference = 'system' | ThemeMode

/**
 * Полный набор токенов одного дизайна для обеих цветовых вариаций.
 *
 * Каждый дизайн обязан предоставить обе вариации, чтобы переключение режима
 * не зависело от наличия запасной темы.
 */
export interface ThemeDefinition {
  light: AppTheme
  dark: AppTheme
}

/**
 * Реестр всех доступных дизайнов.
 *
 * Тип `Record` намеренно связывает ключи реестра с `ThemeName`: забытый
 * экспорт или незарегистрированный дизайн обнаруживается на этапе проверки
 * типов, а не во время рендера.
 */
export type ThemeRegistry = Record<ThemeName, ThemeDefinition>
