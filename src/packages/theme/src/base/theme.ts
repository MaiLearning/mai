/**
 * Шкала оттенков Radix из 12 позиций [0..11].
 * Позиции соответствуют ролям Radix: 1–2 — фон, 3–5 — подложки,
 * 6–8 — границы и интерактивные состояния, 9–10 — solid-цвет,
 * 11–12 — контрастный текст.
 */
export type ColorScale = readonly [
  string,
  string,
  string,
  string,
  string,
  string,
  string,
  string,
  string,
  string,
  string,
  string,
]

/**
 * Набор примитивных цветовых шкал конкретной темы.
 * Палитра используется при сборке темы, но не является её семантическим API.
 */
export interface Palette {
  gray: ColorScale
  accent: ColorScale
  background: string
  success: ColorScale
  warning: ColorScale
  danger: ColorScale
  info: ColorScale
}

/**
 * Типовой контракт темы приложения: полный словарь повторяющихся значений,
 * из которых собран UI. Каждая тема (светлая, тёмная и т.д.) обязана
 * реализовать все ключи — это гарантирует, что компоненты не найдут
 * отсутствующего токена.
 */
export interface AppTheme {
  /** Цвета текста. Группа отвечает только за читаемое содержимое, а не за фон или рамку. */
  text: {
    /** Основной цвет текста на стандартном фоне приложения. */
    primary: string
    /** Вторичный текст: подписи, пояснения и менее важная мета-информация. */
    muted: string
    /** Цвет текста на акцентном фоне, например на основной кнопке. */
    onPrimary: string
    /** Цвет текста и иконок, которым нужно показать акцентное действие. */
    accent: string
  }
  /** Задний план приложения и компонентов, включая визуальные состояния. */
  background: {
    /** Базовый фон страницы и полей ввода. */
    body: string
    /** Обычный фон самостоятельного компонента: карточки, панели, модального окна. */
    surface: string
    /**
     * Приподнятый слой — элемент на карточке, которому нужен контраст с ней:
     * вторичная кнопка, футёр модалки, чип на карточке, шеврон списка.
     * Светлее/темнее surface на одну ступень, но не выше hover.
     */
    raised: string
    /**
     * Вдавленный слой — содержимое ниже базового: дроп-зоны, колодцы,
     * поле правки внутри карточки. Визуально «вглубь» относительно surface.
     */
    sunken: string
    /** Фон элемента, поднятого над обычной поверхностью: popup, dropdown или overlay. */
    elevated: string
    /** Базовый фон акцентного компонента. */
    accent: string
    /** Фон акцентного компонента при наведении. */
    accentHover: string
    /** Мягкая акцентная подложка без высокой визуальной тяжести. */
    accentSubtle: string
    /**
     * Наведение — курсор над элементом, но кнопка мыши не нажата.
     * Самый мягкий отклик: подсказывает, что элемент кликабелен.
     * Отличается от active тем, что active — это момент самого нажатия.
     */
    hover: string
    /**
     * Текущее нажатие — кнопка мыши зажата (:active), либо элемент
     * «залип» в нажатом состоянии (например, раскрытый аккордеон).
     * Более плотный фон, чем hover: усиливает ощущение вдавленности.
     */
    active: string
    /**
     * Выбор — элемент отмечен как текущий в списке/навигации
     * (aria-selected, активный пункт меню, выбранная вкладка).
     * Стойкое состояние, сохраняется и без наведения; обычно
     * брендированная подложка, чтобы выделяться среди hover-фонов.
     */
    selected: string
    /**
     * Недоступность — элемент отключён (:disabled) и не реагирует
     * на взаимодействия. Равен rest-фону поверхности: недоступность
     * доносит приглушённый текст, а не сама подложка.
     */
    disabled: string
  }
  /** Линии, разделители и обводки компонентов. */
  border: {
    /** Обычная граница нейтрального компонента. */
    default: string
    /** Усиленная граница для hover, раскрытого или выделенного элемента. */
    strong: string
    /** Акцентная граница выбранного или сфокусированного элемента. */
    accent: string
  }
  /** Цвета, сообщающие результат или смысл состояния компонента. */
  status: {
    /** Успешное выполнение, подтверждение или завершённое действие. */
    success: {
      /** Цвет текста, иконки или рамки успешного состояния. */
      foreground: string
      /** Мягкая подложка успешного состояния. */
      background: string
    }
    /** Предупреждение, требующее внимания, но не блокирующее действие. */
    warning: {
      /** Цвет текста, иконки или рамки предупреждения. */
      foreground: string
      /** Мягкая подложка предупреждения. */
      background: string
    }
    /** Ошибка, опасное действие или критическое состояние. */
    danger: {
      /** Цвет текста, иконки или рамки ошибки. */
      foreground: string
      /** Мягкая подложка ошибки. */
      background: string
    }
    /** Нейтральное информационное сообщение или подсказка. */
    info: {
      /** Цвет текста, иконки или рамки информационного состояния. */
      foreground: string
      /** Мягкая подложка информационного состояния. */
      background: string
    }
  }
  /** Индикаторы клавиатурного и программного фокуса. */
  focus: {
    /** Цвет кольца `:focus-visible` вокруг интерактивного элемента. */
    ring: string
  }
  typography: {
    fontFamily: string
    fontFamilyMonospace: string
    sizes: {
      xs: string
      sm: string
      md: string
      lg: string
      xl: string
    }
    weights: {
      regular: number
      medium: number
      semibold: number
      bold: number
    }
    lineHeights: {
      tight: number
      normal: number
      relaxed: number
    }
  }
  spacing: {
    xs: string
    sm: string
    md: string
    lg: string
    xl: string
  }
  radius: {
    sm: string
    md: string
    lg: string
    full: string
  }
  shadows: {
    sm: string
    md: string
    lg: string
  }
  zIndex: {
    popover: number
    toast: number
    modal: number
  }
  durations: {
    fast: string
    normal: string
    slow: string
  }
  breakpoints: {
    sm: string
    md: string
    lg: string
    xl: string
  }
}
